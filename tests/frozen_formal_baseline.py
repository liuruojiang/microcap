"""Read-only regression inputs, authenticated by an existing delivery manifest.

This deliberately does not certify today's freshness or a changed source tree.
MICROCAP_TEST_DATA_ROOT may select a separately refreshed, immutable checkout.
No historical proof, production output or manifest is generated by this helper.
"""
from __future__ import annotations

import hashlib
import json
import os
from dataclasses import replace
from pathlib import Path

from scripts import top100_delivery as delivery


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def data_root() -> Path:
    return Path(os.environ.get("MICROCAP_TEST_DATA_ROOT", Path(__file__).resolve().parents[1])).resolve()


def load_frozen_formal_baseline(root: Path | None = None) -> dict:
    root = (root or data_root()).resolve()
    manifest_path = root / delivery.MANIFEST
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest.get("ok") is True and manifest.get("status") == "complete", (
        "A complete pre-existing delivery baseline is required", manifest_path)
    assert manifest.get("scope") == "whole_workspace_delivery"
    target = manifest["expected_date"]
    parsed_target = delivery.state._parse_date(target)
    assert parsed_target is not None and parsed_target.isoformat() == target, (
        "Invalid recorded baseline date", target)
    # Authenticate the entire recorded snapshot, including its original source
    # provenance. The currently imported code is independently exercised below;
    # do not rewrite old manifest hashes to pretend that it generated this data.
    expected = {**manifest["inputs"], **manifest["artifacts"]}
    for name, expected_hash in expected.items():
        path = (root / name).resolve()
        assert path.is_relative_to(root), name
        # Delivery authenticates CRLF/LF-equivalent content. Preserve that exact
        # contract, then separately pin raw bytes for read-only teardown checks.
        assert delivery.sha(path) == expected_hash, f"Frozen delivery baseline hash mismatch: {name}"
    report = delivery.inspect_outputs(root, target)
    assert report["ok"], report["errors"]
    for key in ("inputs", "artifacts", "streams", "expected_date"):
        assert report[key] == manifest[key], f"Frozen delivery baseline mismatch: {key}"
    expected = {name: digest(root / name) for name in expected}
    expected[delivery.MANIFEST] = digest(manifest_path)
    base_summary = delivery.state.REQUIRED_FILES[1]
    expected[base_summary] = digest(root / base_summary)
    aliases = {
        "panel": delivery.BASE_PANEL,
        "proxy_index": delivery.BASE_FILES["proxy_index"],
        "turnover": delivery.BASE_FILES["proxy_turnover"],
        "base_costed_nav": delivery.BASE_FILES["costed_nav"],
        "v20_nav": "microcap_top100_mom16_biweekly_live_v2_0_nav.csv",
        "v23_costed_nav": delivery.COSTED["3"],
        "v25_costed_nav": delivery.COSTED["5"],
    }
    snapshot = {
        "scope": "frozen_regression_only",
        "latest_completed_session": target,
        "same_day_freshness_certified_by_this_fixture": False,
        "recorded_manifest_verified_at": manifest["verified_at"],
        "recorded_release_sha": manifest["release_sha"],
        "manifest_sha256": expected[delivery.MANIFEST],
        "artifacts": {
            key: {"path": str(root / "outputs" / name),
                  "date_field": "rebalance_date" if key == "turnover" else "date",
                  "rows": report["streams"][name]["rows"],
                  "latest_date": report["streams"][name]["latest_date"],
                  "manifest_content_sha256": report["streams"][name]["sha256"],
                  "raw_sha256": digest(root / "outputs" / name)}
            for key, name in aliases.items()
        },
    }
    return {"root": root, "target": target, "report": report,
            "snapshot": snapshot, "hashes": expected}


def assert_frozen_baseline_unchanged(baseline: dict) -> None:
    for name, expected_hash in baseline["hashes"].items():
        assert digest(baseline["root"] / name) == expected_hash, f"Frozen baseline changed: {name}"


def redirect_native_base_paths(patch, root: Path, version: str) -> None:
    """Let native freshness/lineage code read the selected immutable inputs.

    Only path resolution changes. Native date, row, continuity, hash and lineage
    validators still execute; no successful freshness result is fabricated.
    """
    import microcap_top100_mom16_biweekly_live_v2_0 as v20

    original = v20._resolve_base_paths()
    resolved = replace(
        original,
        panel_path=root / "outputs" / delivery.BASE_PANEL,
        index_csv=root / "outputs" / delivery.BASE_FILES["proxy_index"],
        costed_nav_csv=root / "outputs" / delivery.BASE_FILES["costed_nav"],
        output_paths={key: root / "outputs" / value.name for key, value in original.output_paths.items()},
    )
    namespaces = (v20.__dict__, v20._resolve_base_paths.__globals__,
                  v20.overlay_mod.current_data_state_fingerprint.__globals__)
    seen = set()
    for namespace in namespaces:
        if id(namespace) not in seen:
            seen.add(id(namespace))
            patch.setitem(namespace, "_resolve_base_paths", lambda *args, **kwargs: resolved)
    if version != "0":
        # v2.3/v2.5 regenerate only their own temporary bundle. Their real
        # post-promotion guard must also read the authenticated upstream v2.0
        # final stream, not a different checkout's older display export.
        for namespace in (v20.__dict__, v20.overlay_mod.current_data_state_fingerprint.__globals__):
            patch.setitem(namespace, "COSTED_NAV_CSV", root / "outputs" / delivery.COSTED["0"])
            patch.setitem(namespace, "SUMMARY_JSON", root / "outputs" /
                          "microcap_top100_mom16_biweekly_live_v2_0_summary.json")


